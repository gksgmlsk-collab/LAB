def bullets(doc, section, items):
    for item in items:
        body(doc, section, f"• {item}")


def add_table(doc, section, headers, rows, *, width=CONTENT_WIDTH, tall_rows=None):
    tall_rows = set(tall_rows or [])
    table = doc.add_table(rows=len(rows) + 1, cols=len(headers), section=section, width=width)
    for col, value in enumerate(headers):
        table.set_cell_text(0, col, str(value))
    for row_index, row in enumerate(rows, start=1):
        for col, value in enumerate(row):
            table.set_cell_text(row_index, col, str(value))
            if row_index in tall_rows:
                try:
                    table.cell(row_index, col).set_size(height=5200)
                except Exception:
                    pass
    return table


def screenshot_grid(doc, section, items, *, cols=2, box_height=6700, prefix="앱 화면 삽입"):
    """Create large, editable table cells that serve as screenshot insertion slots."""
    rows_per_group = 2
    groups = ceil(len(items) / cols)
    table = doc.add_table(rows=groups * rows_per_group, cols=cols, section=section, width=CONTENT_WIDTH)
    index = 0
    for group in range(groups):
        image_row = group * 2
        evidence_row = image_row + 1
        for col in range(cols):
            if index >= len(items):
                table.set_cell_text(image_row, col, "")
                table.set_cell_text(evidence_row, col, "")
                index += 1
                continue
            item = items[index]
            title = item[0] if isinstance(item, tuple) else str(item)
            evidence = item[1] if isinstance(item, tuple) and len(item) > 1 else "화면에서 확인할 신호 → 바뀐 결정 → 같은 지표 재확인"
            placeholder = (
                f"【{prefix} {index + 1}】 {title}\n\n"
                "여기에 실제 사용 화면을 삽입하세요.\n"
                "학교명·학생명·계정·URL·QR·개인정보는 블라인드 처리"
            )
            table.set_cell_text(image_row, col, placeholder)
            table.set_cell_text(evidence_row, col, f"증거 캡션: {evidence}")
            try:
                table.cell(image_row, col).set_size(height=box_height)
                table.cell(evidence_row, col).set_size(height=1800)
            except Exception:
                pass
            index += 1
    return table


